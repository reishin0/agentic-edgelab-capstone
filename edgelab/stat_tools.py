"""Deterministic, in-sample-only tools for the synthetic checkpoint exercise."""

from dataclasses import asdict, dataclass
from datetime import date, timedelta
from importlib.metadata import PackageNotFoundError, version
import math
import random
import sys
import warnings

from .contracts import fingerprint


TOOL_SEQUENCE = ("diagnostics", "engle_granger", "stability")
CASES = ("shared-trend", "independent", "structural-break", "spread-level-shift")
ALPHA = 0.05
CRITIC_VERSION = "stat-critic-v1"
SYNTHETIC_SEED = 721
MIN_SAMPLE = 80
MAX_HISTORICAL_SAMPLE = 2000


@dataclass(frozen=True, slots=True)
class Window:
    start: str
    end: str
    as_of: str
    holdout_start: str


@dataclass(frozen=True, slots=True)
class Point:
    day: str
    a: float
    b: float


def synthetic(case: str) -> tuple[Point, ...]:
    if case not in CASES:
        raise ValueError("Unsupported synthetic case")
    rng = random.Random(SYNTHETIC_SEED)
    x = y = noise = 0.0
    rows = []
    for i in range(240):
        x += rng.gauss(0, 1)
        y += rng.gauss(0, 1)
        noise = 0.40 * noise + rng.gauss(0, 0.6)
        slope = -1.2 if case == "structural-break" and i >= 95 else 1.3
        b = y if case == "independent" else slope * x + noise
        # Shift the intercept halfway through formation without reversing the common trend.
        if case == "spread-level-shift" and i >= 90:
            b += 1.2
        rows.append(Point(str(date(2020, 1, 1) + timedelta(days=i)), x, b))
    return tuple(rows)


def window_for_demo() -> Window:
    # Blinded metadata only; no sample values are generated by planning.
    origin = date(2020, 1, 1)
    return Window(str(origin), str(origin + timedelta(days=179)),
                  str(origin + timedelta(days=179)), str(origin + timedelta(days=180)))


def canonical_day(label: str) -> date:
    day = date.fromisoformat(label)
    if str(day) != label:
        raise ValueError("Window dates must be canonical YYYY-MM-DD")
    return day


def check_window(window: Window) -> None:
    start, end, as_of, holdout = map(canonical_day, (window.start, window.end, window.as_of, window.holdout_start))
    if not start <= end <= as_of or end >= holdout:
        raise ValueError("Requested window violates as-of or locked holdout boundary")


def check_sessions(sessions: tuple[str, ...], window: Window) -> None:
    check_window(window)
    if (not MIN_SAMPLE <= len(sessions) <= MAX_HISTORICAL_SAMPLE
            or sessions[0] != window.start or sessions[-1] != window.end):
        raise ValueError("Session calendar does not cover the approved window")
    dates = tuple(map(canonical_day, sessions))
    if any(left >= right for left, right in zip(dates, dates[1:])):
        raise ValueError("Session calendar must be strictly increasing")


def guarded_rows(rows: tuple[Point, ...], window: Window, *,
                 sessions: tuple[str, ...] | None = None) -> tuple[Point, ...]:
    if sessions is not None:
        check_sessions(sessions, window)
        if tuple(row.day for row in rows) != sessions:
            raise ValueError("Historical rows do not exactly match the approved session calendar")
        if any(not math.isfinite(row.a) or not math.isfinite(row.b) for row in rows):
            raise ValueError("Historical sample contains non-finite observations")
        return rows
    check_window(window)
    sample = tuple(row for row in rows if window.start <= row.day <= window.end)
    if (not MIN_SAMPLE <= len(sample) <= 240 or sample[0].day != window.start or sample[-1].day != window.end
            or any(date.fromisoformat(b.day) - date.fromisoformat(a.day) != timedelta(days=1)
                   for a, b in zip(sample, sample[1:]))
            or any(not math.isfinite(row.a) or not math.isfinite(row.b) for row in sample)):
        raise ValueError("Invalid synthetic sample coverage or values")
    return sample


def sample_fingerprint(sample: tuple[Point, ...]) -> str:
    return fingerprint([asdict(row) for row in sample])


def numerical_runtime() -> dict[str, str]:
    try:
        return {"python": sys.version, "platform": sys.platform,
                **{package: version(package) for package in ("statsmodels", "numpy", "scipy")}}
    except PackageNotFoundError:
        raise RuntimeError("Install the project's research extra before numerical execution") from None


def integration_order(level: dict, difference: dict) -> str:
    def stationary(test: dict) -> bool:
        return test["adf_p"] < ALPHA <= test["kpss_p"]

    if stationary(level):
        return "I(0)"
    if level["kpss_p"] < ALPHA <= level["adf_p"] and stationary(difference):
        return "I(1)"
    return "unresolved"


def _root_tests(series, lag_policy: str) -> dict:
    from statsmodels.tsa.stattools import adfuller, kpss

    with warnings.catch_warnings(record=True) as seen:
        warnings.simplefilter("always")
        adf = adfuller(series, maxlag=6, regression="c", autolag=lag_policy)
        k = kpss(series, regression="c", nlags="auto")
    return {"adf_stat": float(adf[0]), "adf_p": float(adf[1]), "adf_lags": int(adf[2]),
            "kpss_stat": float(k[0]), "kpss_p": float(k[1]), "kpss_lags": int(k[2]),
            "warning_categories": sorted({w.category.__name__ for w in seen})}


def _regression(y, x):
    from statsmodels.api import OLS, add_constant

    return OLS(y, add_constant(x, has_constant="add")).fit()


def _cointegration(y, x, lag_policy: str) -> dict:
    from statsmodels.tsa.stattools import adfuller, coint

    fit = _regression(y, x)
    t, p, critical = coint(y, x, trend="c", method="aeg", maxlag=6, autolag=lag_policy)
    # The ordinary ADF supplies the selected lag only, never the cointegration p-value.
    lag = adfuller(fit.resid, maxlag=6, regression="n", autolag=lag_policy)[2]
    return {"stat": float(t), "p": float(p), "critical_values": critical.tolist(),
            "residual_lag": int(lag), "intercept": float(fit.params[0]), "slope": float(fit.params[1])}


def _stability(a, b) -> dict:
    import numpy as np
    from statsmodels.api import OLS, add_constant
    from statsmodels.stats.diagnostic import breaks_cusumolsresid

    fit = _regression(a, b)
    stat, p, _ = breaks_cusumolsresid(fit.resid, ddof=2)
    ecm = OLS(np.diff(a)[1:], add_constant(np.column_stack(
        [fit.resid[1:-1], np.diff(b)[1:], np.diff(a)[:-1]]
    ), has_constant="add")).fit()
    phi = float(_regression(fit.resid[1:], fit.resid[:-1]).params[1])
    return {"cusum_stat": float(stat), "cusum_p": float(p), "ecm_loading": float(ecm.params[1]),
            "ecm_loading_p": float(ecm.pvalues[1]), "ar1_phi": phi,
            "ou_half_life_observations": -math.log(2) / math.log(phi) if 0 < phi < 1 else None}


def compute(tool: str, rows: tuple[Point, ...], window: Window, lag_policy: str, *,
            sessions: tuple[str, ...] | None = None) -> dict:
    if tool not in TOOL_SEQUENCE or lag_policy not in {"AIC", "BIC"}:
        raise ValueError("Tool or lag policy is not allowlisted")
    sample = guarded_rows(rows, window, sessions=sessions)
    runtime = numerical_runtime()
    import numpy as np

    a, b = np.asarray([(row.a, row.b) for row in sample]).T
    if tool == "diagnostics":
        result = {}
        for label, series in (("a", a), ("b", b)):
            level = _root_tests(series, lag_policy)
            difference = _root_tests(np.diff(series), lag_policy)
            result[label] = {"level": level, "difference": difference, "order": integration_order(level, difference)}
    elif tool == "engle_granger":
        result = {"a_on_b": _cointegration(a, b, lag_policy), "b_on_a": _cointegration(b, a, lag_policy)}
    else:
        result = _stability(a, b)
    config = {"tool": tool, "lag_policy": lag_policy, "alpha": ALPHA, "window": asdict(window),
              "n": len(sample), **runtime, "sample_sha256": sample_fingerprint(sample)}
    # Refuse NaN/Inf before an observation can be recorded as a successful result.
    return {"config": config, "config_sha256": fingerprint(config), "result": result,
            "result_sha256": fingerprint(result)}


def _pvalue(value: object) -> float:
    if type(value) not in {int, float} or not 0 <= value <= 1:
        raise ValueError("Expected a finite probability between zero and one")
    return float(value)


def review(tool: str, observation: object) -> tuple[str, str]:
    finding = assess(tool, observation)
    return finding["decision"], finding["reason"]


def assess(tool: str, observation: object) -> dict:
    def finding(rule: str, decision: str, reason: str, **details) -> dict:
        return {"critic_version": CRITIC_VERSION, "rule_id": rule, "decision": decision,
                "reason": reason, "details": details}

    if not isinstance(observation, dict) or "error" in observation:
        return finding("NO_OBSERVATION", "unresolved", "The approved tool produced no usable observation.")
    try:
        return _review_result(tool, observation["result"], finding)
    except (KeyError, TypeError, ValueError):
        return finding("INVALID_EVIDENCE", "unresolved", "The approved tool observation was incomplete or invalid.")


def _review_result(tool: str, values: dict, finding) -> dict:
    if tool == "diagnostics":
        series = {}
        for label in ("a", "b"):
            evidence = values[label]
            tests = {stage: {field: _pvalue(evidence[stage][field]) for field in ("adf_p", "kpss_p")}
                     for stage in ("level", "difference")}
            order = integration_order(tests["level"], tests["difference"])
            series[label] = {**tests, "derived_order": order, "reported_order": evidence["order"]}
        details = {"alpha": ALPHA, "series": series}
        if any(row["derived_order"] != row["reported_order"] for row in series.values()):
            return finding("ROOT_LABEL_MISMATCH", "unresolved",
                           "A reported integration order contradicts its ADF/KPSS evidence.", **details)
        orders = {row["derived_order"] for row in series.values()}
        if orders == {"I(1)"}:
            return finding("ROOT_BOTH_I1", "proceed", "Both series met the declared I(1) prerequisite.", **details)
        if "unresolved" in orders:
            return finding("ROOT_INCONCLUSIVE", "unresolved", "ADF and KPSS did not establish the prerequisites.", **details)
        if orders == {"I(0)"}:
            return finding("ROOT_BOTH_I0", "revise",
                           "Both series appear stationary; a levels protocol requires new approval.", **details)
        return finding("ROOT_MIXED", "stop",
                       "Integration orders differ; the approved cointegration route does not apply.", **details)
    if tool == "engle_granger":
        pvalues = {direction: _pvalue(values[direction]["p"]) for direction in ("a_on_b", "b_on_a")}
        decisions = {p < ALPHA for p in pvalues.values()}
        if len(decisions) != 1:
            return finding("EG_DISAGREEMENT", "unresolved", "The directional tests disagree.", alpha=ALPHA, **pvalues)
        if True in decisions:
            return finding("EG_BOTH_REJECT", "proceed", "Both directions reject no cointegration; assess stability.",
                           alpha=ALPHA, **pvalues)
        return finding("EG_NEITHER_REJECTS", "stop", "Neither direction rejects no cointegration at the declared threshold.",
                       alpha=ALPHA, **pvalues)
    if tool == "stability":
        p = _pvalue(values["cusum_p"])
        if p < ALPHA:
            return finding("CUSUM_REJECTS", "stop", "CUSUM detected evidence of in-sample instability.",
                           alpha=ALPHA, cusum_p=p)
        loading, phi = values["ecm_loading"], values["ar1_phi"]
        ecm_p = _pvalue(values["ecm_loading_p"])
        if any(type(v) not in (float, int) or not math.isfinite(v) for v in (loading, phi)):
            raise ValueError("Invalid ECM/AR(1) diagnostics")
        half_life = values["ou_half_life_observations"]
        if 0 < phi < 1:
            expected = -math.log(2) / math.log(phi)
            if type(half_life) not in (int, float) or not math.isclose(half_life, expected, rel_tol=1e-9):
                raise ValueError("Inconsistent AR(1) half-life")
        elif half_life is not None:
            raise ValueError("OU half-life is not applicable")
        return finding("CUSUM_NOT_REJECTED", "continue",
                       "CUSUM did not detect a break. ECM/OU are descriptive; stability and mean reversion are not established. Holdout untested.",
                       alpha=ALPHA, cusum_p=p, ecm_loading=loading, ecm_loading_p=ecm_p,
                       ar1_phi=phi, ou_half_life_observations=half_life)
    raise ValueError("Unknown statistical tool")
